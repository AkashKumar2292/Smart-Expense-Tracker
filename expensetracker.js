window.processRecurringBills = async function() {
    if (!currentUserUid) return;

    const now = new Date();
    const todayTime = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();

    const parents = transactions.filter(t => t.recurring && t.recurring !== 'none' && !t.isAutoGenerated);
    let generatedCount = 0;

    for (const parent of parents) {
        const pParts = parent.date.split('-');
        let currDate = new Date(pParts[0], pParts[1] - 1, pParts[2]);
        let expectedDates = [];

        while (true) {
            if (parent.recurring === 'daily') {
                currDate.setDate(currDate.getDate() + 1);
            } else if (parent.recurring === 'weekly') {
                currDate.setDate(currDate.getDate() + 7);
            } else if (parent.recurring === 'monthly') {
                currDate.setMonth(currDate.getMonth() + 1);
            } else if (parent.recurring === 'yearly') {
                currDate.setFullYear(currDate.getFullYear() + 1);
            }

            if (currDate.getTime() > todayTime) break;

            const expectedDateStr = `${currDate.getFullYear()}-${String(currDate.getMonth() + 1).padStart(2, '0')}-${String(currDate.getDate()).padStart(2, '0')}`;
            expectedDates.push(expectedDateStr);
        }

        for (const expectedDate of expectedDates) {
            const exists = transactions.some(t => 
                (t.parentId === parent.id || t.description === `[Auto-Recurring] ${parent.description || ''}`) && 
                t.date === expectedDate
            );

            if (!exists) {
                const autoTx = {
                    id: Date.now() + Math.floor(Math.random() * 1000), 
                    date: expectedDate,
                    category: parent.category,
                    amount: parent.amount,
                    status: "Success",
                    type: parent.type || (parent.amount > 0 ? "income" : "expense"),
                    description: `[Auto-Recurring] ${parent.description || ''}`,
                    recurring: 'none', 
                    isAutoGenerated: true,
                    parentId: parent.id 
                };

                try {
                    const docRef = await addDoc(collection(db, "users", currentUserUid, "transactions"), autoTx);
                    autoTx.docId = docRef.id;
                    transactions.unshift(autoTx);
                    generatedCount++;
                } catch(e) { console.error("Error auto-billing", e); }
            }
        }
    }
    
    if (generatedCount > 0) {
        showNotification(`${generatedCount} recurring transactions auto-generated up to today.`, "info");
    }
};

