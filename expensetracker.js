window.confirmStopRecurring = async function(action) {
    const docId = document.getElementById('stopRecurringDocId').value;
    const txId = parseInt(document.getElementById('stopRecurringTxId').value);
    
    const tx = transactions.find(t => t.id === txId);
    if (!tx) return;

    tx.recurring = 'none';
    if (currentUserUid && docId) {
        try { await updateDoc(doc(db, "users", currentUserUid, "transactions", docId), { recurring: 'none' }); }
        catch(e) { console.error(e); }
    }

    if (action === 'delete') {
        const children = transactions.filter(t => 
            t.parentId === txId || 
            (t.isAutoGenerated && t.description === `[Auto-Recurring] ${tx.description || ''}` && t.category === tx.category)
        );

        for (const child of children) {
            transactions = transactions.filter(t => t.id !== child.id);
            if (currentUserUid && child.docId) {
                try { await deleteDoc(doc(db, "users", currentUserUid, "transactions", child.docId)); }
                catch(e) { console.error(e); }
            }
        }
        showNotification("Recurrence stopped & generated history deleted.", "success");
    } else {
        showNotification("Recurrence stopped (Past history kept).", "success");
    }

    window.closeModal('stopRecurringModal');
    updateDashboard();
    updateTransactionsTable();
};

