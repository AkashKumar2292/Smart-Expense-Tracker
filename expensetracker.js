window.calculateSavingsCompare = function() {
    const y1 = document.getElementById('savingsCompare1').value;
    const y2 = document.getElementById('savingsCompare2').value;
    const resultBox = document.getElementById('savingsCompareResult');
    if (!resultBox) return;
    if (!y1 || !y2) { resultBox.innerHTML = '<span style="font-size: 0.875rem; color: rgba(255,255,255,0.8);">Select two years to compare</span>'; return; }
    if (y1 === y2) { resultBox.innerHTML = '<span style="font-size: 0.875rem; color: #f87171;">Cannot compare the same year.</span>'; return; }

    let y1Saved = 0; let y2Saved = 0;
    transactions.forEach(t => {
        const year = t.date.substring(0,4);
        if (year === y1) y1Saved += t.amount;
        if (year === y2) y2Saved += t.amount;
    });
    const diff = y1Saved - y2Saved;
    const isPositive = diff >= 0;
    resultBox.innerHTML = `
        <div style="font-size: 0.75rem; color: rgba(255,255,255,0.8); margin-bottom: 0.25rem;">${y1} vs ${y2}</div>
        <div style="font-size: 1.25rem; font-weight: bold; color: ${isPositive ? '#34d399' : '#f87171'};">${isPositive ? '<i class="fas fa-arrow-up"></i>' : '<i class="fas fa-arrow-down"></i>'} ${userCurrency}${Math.abs(diff).toLocaleString()}</div>
        <div style="font-size: 0.7rem; color: rgba(255,255,255,0.7); margin-top: 0.25rem;">${isPositive ? `You saved more in ${y1}` : `You saved less in ${y1}`}</div>
    `;
}

