function updateTransactionsTable() {
    const tbody = document.querySelector(".transactions-table tbody"); 
    tbody.innerHTML = "";
    let dataToShow = [...transactions];

    if (window.selectedTableCategories && window.selectedTableCategories.length > 0) {
        dataToShow = dataToShow.filter(t => window.selectedTableCategories.includes(t.category));
    }

    if (currentFilter.type !== 'all' && currentFilter.value) {
        dataToShow = dataToShow.filter(t => {
            if (currentFilter.type === 'date') return t.date === currentFilter.value; 
            else if (currentFilter.type === 'month' || currentFilter.type === 'year') return t.date.startsWith(currentFilter.value); 
            return true;
        });
    }

    if (currentSort.column === 'amount') {
        dataToShow.sort((a, b) => {
            let valA = Math.abs(a.amount); let valB = Math.abs(b.amount);
            if (valA < valB) return currentSort.direction === 'asc' ? -1 : 1;
            if (valA > valB) return currentSort.direction === 'asc' ? 1 : -1;
            return 0;
        });
    } else {
        dataToShow.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
    }

    dataToShow.forEach((transaction) => {
        const row = document.createElement("tr");
        const formattedDate = new Date(transaction.date).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
        let amountDisplay = transaction.amount > 0 ? `+${userCurrency}${transaction.amount.toLocaleString()}.00` : `-${userCurrency}${Math.abs(transaction.amount).toLocaleString()}.00`;

        const recurringVal = transaction.recurring === true ? 'monthly' : (transaction.recurring === false ? 'none' : (transaction.recurring || 'none'));
        const isRecur = recurringVal !== 'none';
        
        let actionButtons = '';

        if (transaction.isAutoGenerated) {
            actionButtons = `
                <button class="action-btn" title="Auto-Generated (Edit Original)" disabled style="opacity: 0.5; cursor: not-allowed;">
                    <i class="fas fa-repeat" style="color: #9ca3af;"></i>
                </button>
                <button class="action-btn" onclick="window.deleteTransaction('${transaction.docId}', ${transaction.id})" title="Delete Transaction">
                    <i class="fas fa-trash-alt" style="color: #ef4444;"></i>
                </button>
            `;
        } else {
            const recurIconColor = isRecur ? '#3b82f6' : '#9ca3af';
            const recurTooltip = isRecur ? `Recurring ${recurringVal.toUpperCase()} (Click to manage)` : 'Make Recurring';
            
            actionButtons = `
                <button class="action-btn" onclick="window.toggleRecurring('${transaction.docId}', ${transaction.id})" title="${recurTooltip}">
                    <i class="fas fa-repeat" style="color: ${recurIconColor};"></i>
                </button>
                <button class="action-btn" onclick="window.deleteTransaction('${transaction.docId}', ${transaction.id})" title="Delete Transaction">
                    <i class="fas fa-trash-alt" style="color: #ef4444;"></i>
                </button>
            `;
        }

        row.innerHTML = `
            <td>${formattedDate}</td>
            <td>${transaction.category}</td>
            <td style="color: ${transaction.amount > 0 ? "#10b981" : "#ef4444"}">${amountDisplay}</td>
            <td><span class="status-success">${transaction.status}</span></td>
            <td style="display: flex; gap: 0.5rem; border-bottom: none;">
                ${actionButtons}
            </td>
        `;
        tbody.appendChild(row);
    });

    if (dataToShow.length === 0) tbody.innerHTML = `<tr><td colspan="5" style="text-align: center; padding: 2rem; color: #6b7280;">No transactions found for this period.</td></tr>`;
    updateSortIcons();
}

