// --- HELPER FUNCTION: Sort Categories with "Other" Always Last ---
function sortCategoriesWithOtherLast(categoriesArray) {
    return categoriesArray.slice().sort((a, b) => {
        if (a === 'Other') return 1;
        if (b === 'Other') return -1;
        return a.localeCompare(b);
    });
}

