window.exportData = function() { 
    if (transactions.length === 0) { showNotification("No transactions to export!", "error"); return; }

    const headers = ["Date", "Category", "Description", "Type", "Amount", "Status", "Is Recurring"];
    const rows = transactions.map(t => [
        t.date, t.category, `"${t.description || ''}"`, t.type || (t.amount > 0 ? "income" : "expense"),
        Math.abs(t.amount), t.status, (t.recurring && t.recurring !== 'none') ? t.recurring : "No"
    ]);

    const csvContent = [headers, ...rows].map(e => e.join(",")).join("\n");
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement("a");
    link.setAttribute("href", URL.createObjectURL(blob));
    link.setAttribute("download", `My_Expenses_${new Date().toLocaleDateString()}.csv`);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    showNotification("CSV Exported successfully!", "success");
}

