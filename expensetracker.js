function updateDashboard() {
    const now = new Date();
    const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1).getTime();
    const startOfLastMonth = new Date(now.getFullYear(), now.getMonth() - 1, 1).getTime();
    let thisMonthInc = 0, lastMonthInc = 0, thisMonthExp = 0, lastMonthExp = 0;

    transactions.forEach(t => {
        const parts = t.date.split('-');
        const tTime = new Date(parts[0], parts[1] - 1, parts[2]).getTime();
        const amt = Math.abs(t.amount);
        
        if (tTime >= startOfMonth) { 
            if (t.amount > 0) thisMonthInc += amt; 
            else thisMonthExp += amt; 
        } else if (tTime >= startOfLastMonth && tTime < startOfMonth) { 
            if (t.amount > 0) lastMonthInc += amt; 
            else lastMonthExp += amt; 
        }
    });

    document.getElementById("incomeAmountDisplay").textContent = `${userCurrency}${thisMonthInc.toLocaleString()}.00`;
    document.getElementById("expenseAmountDisplay").textContent = `${userCurrency}${thisMonthExp.toLocaleString()}.00`;

    let incChange = 0;
    if (lastMonthInc === 0) incChange = thisMonthInc > 0 ? 100 : 0;
    else incChange = ((thisMonthInc - lastMonthInc) / lastMonthInc) * 100;

    let expChange = 0;
    if (lastMonthExp === 0) expChange = thisMonthExp > 0 ? 100 : 0;
    else expChange = ((thisMonthExp - lastMonthExp) / lastMonthExp) * 100;

    const incChangeEl = document.getElementById('incomeChange');
    if (thisMonthInc === 0 && lastMonthInc === 0) { incChangeEl.innerHTML = `<i class="fas fa-minus"></i> 0% vs Last month`; incChangeEl.className = 'change'; } 
    else if (incChange >= 0) { incChangeEl.innerHTML = `<i class="fas fa-arrow-up"></i> ${incChange.toFixed(1)}% vs Last month`; incChangeEl.className = 'change'; } 
    else { incChangeEl.innerHTML = `<i class="fas fa-arrow-down"></i> ${Math.abs(incChange).toFixed(1)}% vs Last month`; incChangeEl.className = 'change2'; }

    const expChangeEl = document.getElementById('expenseChange');
    if (thisMonthExp === 0 && lastMonthExp === 0) { expChangeEl.innerHTML = `<i class="fas fa-minus"></i> 0% vs Last month`; expChangeEl.className = 'change'; } 
    else if (expChange >= 0) { expChangeEl.innerHTML = `<i class="fas fa-arrow-up"></i> ${expChange.toFixed(1)}% vs Last month`; expChangeEl.className = 'change2'; } 
    else { expChangeEl.innerHTML = `<i class="fas fa-arrow-down"></i> ${Math.abs(expChange).toFixed(1)}% vs Last month`; expChangeEl.className = 'change'; }

    let percentage = 0;
    if (monthlyBudgetLimit > 0) percentage = (thisMonthExp / monthlyBudgetLimit) * 100;
    
    if (percentage >= 100) showNotification("ALERT: Budget Exceeded!", "error");
    else if (percentage >= 80) showNotification("Warning: You have used 80% of your budget.", "info");
    
    document.getElementById("budgetLimitDisplay").textContent = `of ${userCurrency}${monthlyBudgetLimit.toLocaleString()}.00 limit`;
    document.getElementById("budgetUsedDisplay").textContent = `${userCurrency}${thisMonthExp.toLocaleString()}.00`;
    
    const progressFill = document.getElementById("budgetProgressFill");
    progressFill.style.width = `${Math.min(percentage, 100)}%`;
    if (percentage >= 100) progressFill.style.background = "#ef4444"; 
    else if (percentage >= 80) progressFill.style.background = "#f97316"; 
    else progressFill.style.background = "#fbbf24"; 

    let allTimeInc = 0, allTimeExp = 0, thisYearInc = 0, thisYearExp = 0;
    const currentYearStr = now.getFullYear().toString();

    transactions.forEach(t => {
        const amt = Math.abs(t.amount);
        const isInc = t.amount > 0;
        if (isInc) allTimeInc += amt; else allTimeExp += amt;
        if (t.date.substring(0,4) === currentYearStr) {
            if (isInc) thisYearInc += amt; else thisYearExp += amt;
        }
    });

    const formatSavings = (val, elId) => {
        const el = document.getElementById(elId);
        if (el) {
            el.textContent = `${val >= 0 ? '+' : '-'}${userCurrency}${Math.abs(val).toLocaleString()}`;
            el.style.color = val >= 0 ? '#34d399' : '#f87171'; 
        }
    };

    formatSavings(lastMonthInc - lastMonthExp, 'savedLastMonth');
    formatSavings(thisYearInc - thisYearExp, 'savedThisYear');
    formatSavings(allTimeInc - allTimeExp, 'savedAllTime');
    
    window.initSavingsCompare();
    updateBreakdowns();
    updateExpenseChart();
}

function updateBreakdowns() {
    const expenseTransactions = transactions.filter(t => t.amount < 0);
    const incomeTransactions = transactions.filter(t => t.amount > 0);
    
    const now = new Date();
    const startOfDay = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
    const dayOfWeek = now.getDay();
    const daysToMonday = dayOfWeek === 0 ? 6 : dayOfWeek - 1; 
    const startOfWeek = startOfDay - (daysToMonday * 24 * 60 * 60 * 1000); 
    const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1).getTime();

    function processBreakdown(txs, dailyId, weeklyId, monthlyId, listId, colorBarId) {
        let daily = 0, weekly = 0, monthly = 0, total = 0;
        const categoryTotals = {};

        txs.forEach(t => {
            const parts = t.date.split('-');
            const tTime = new Date(parts[0], parts[1] - 1, parts[2]).getTime();
            const absAmount = Math.abs(t.amount);
            
            if (tTime >= startOfMonth) {
                monthly += absAmount; 
                total += absAmount;
                if (!categoryTotals[t.category]) categoryTotals[t.category] = 0;
                categoryTotals[t.category] += absAmount;
                if (tTime >= startOfDay) daily += absAmount;
                if (tTime >= startOfWeek) weekly += absAmount;
            }
        });

        document.getElementById(dailyId).textContent = `${userCurrency}${daily.toLocaleString()}.00`;
        document.getElementById(weeklyId).textContent = `${userCurrency}${weekly.toLocaleString()}.00`;
        document.getElementById(monthlyId).textContent = `${userCurrency}${monthly.toLocaleString()}.00`;

        // Sort by amount, but force 'Other' to be at the bottom
        const sortedCategories = Object.keys(categoryTotals).map(cat => { return { name: cat, amount: categoryTotals[cat] }; }).sort((a, b) => {
            if (a.name === 'Other') return 1;
            if (b.name === 'Other') return -1;
            return b.amount - a.amount;
        });

        const categoriesList = document.getElementById(listId);
        categoriesList.innerHTML = '';
        
        const colors = ['#ea580c', '#f59e0b', '#eab308', '#10b981', '#3b82f6', '#8b5cf6', '#ec4899'];
        let colorBarGradient = [], currentPercentage = 0;

        sortedCategories.forEach((cat, index) => {
            const color = colors[index % colors.length];
            let percentage = 0;
            if (total > 0) percentage = (cat.amount / total) * 100;
            if (percentage > 0) { colorBarGradient.push(`${color} ${currentPercentage}% ${currentPercentage + percentage}%`); currentPercentage += percentage; }

            categoriesList.innerHTML += `
                <li class="expense-category">
                    <div class="category-info"><div class="category-dot" style="background-color: ${color}"></div><span>${cat.name}</span></div>
                    <div style="text-align: right;"><div style="font-weight: 600;">${userCurrency}${cat.amount.toLocaleString()}.00</div><div style="font-size: 0.7rem; color: #6b7280;">${percentage.toFixed(1)}%</div></div>
                </li>
            `;
        });
        const colorBar = document.getElementById(colorBarId);
        if (colorBarGradient.length > 0) colorBar.style.background = `linear-gradient(to right, ${colorBarGradient.join(', ')})`;
        else colorBar.style.background = '#e5e7eb'; 
    }

    processBreakdown(expenseTransactions, 'dailyExpense', 'weeklyExpense', 'monthlyExpense', 'expenseCategoriesList', 'expenseColorBar');
    processBreakdown(incomeTransactions, 'dailyIncome', 'weeklyIncome', 'monthlyIncome', 'incomeCategoriesList', 'incomeColorBar');
}

