window.renderOverviewChart = function() {
    const timeframe = document.getElementById('overviewTimeframe').value;
    const year1 = document.getElementById('overviewYear1').value || new Date().getFullYear().toString();
    const year2 = document.getElementById('overviewYear2').value || 'none';
    const isCompare = year2 !== 'none' && timeframe !== 'yearly'; 
    const titleEl = document.getElementById('overviewMainTitle');

    if (timeframe === 'yearly') { titleEl.textContent = "Yearly Overview"; document.getElementById('overviewComparisonSelectors').style.display = 'none'; } 
    else if (timeframe === 'quarterly') { titleEl.textContent = "Quarterly Overview"; document.getElementById('overviewComparisonSelectors').style.display = 'flex'; } 
    else { titleEl.textContent = "Monthly Overview"; document.getElementById('overviewComparisonSelectors').style.display = 'flex'; }

    let labels = [];
    if (timeframe === 'monthly') labels = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
    else if (timeframe === 'quarterly') labels = ['Q1','Q2','Q3','Q4'];
    else if (timeframe === 'yearly') { 
        labels = [...new Set(transactions.map(t => t.date.substring(0,4)))].sort((a,b)=>a-b); 
        if (labels.length === 0) labels = [new Date().getFullYear().toString()]; 
    }

    let data = {}; labels.forEach(l => { data[l] = { y1Inc: 0, y1Exp: 0, y2Inc: 0, y2Exp: 0 }; });

    transactions.forEach(t => {
        const y = t.date.substring(0,4); const m = parseInt(t.date.substring(5,7)) - 1; 
        const amt = Math.abs(t.amount); const isInc = t.amount > 0;
        if (timeframe === 'yearly') { 
            if (data[y]) { if (isInc) data[y].y1Inc += amt; else data[y].y1Exp += amt; } 
        } else if (timeframe === 'quarterly') {
            const qLabel = labels[Math.floor(m / 3)];
            if (y === year1) { if (isInc) data[qLabel].y1Inc += amt; else data[qLabel].y1Exp += amt; } 
            else if (isCompare && y === year2) { if (isInc) data[qLabel].y2Inc += amt; else data[qLabel].y2Exp += amt; }
        } else if (timeframe === 'monthly') {
            const mLabel = labels[m];
            if (y === year1) { if (isInc) data[mLabel].y1Inc += amt; else data[mLabel].y1Exp += amt; } 
            else if (isCompare && y === year2) { if (isInc) data[mLabel].y2Inc += amt; else data[mLabel].y2Exp += amt; }
        }
    });

    let maxVal = 1; labels.forEach(l => { maxVal = Math.max(maxVal, data[l].y1Inc, data[l].y1Exp, data[l].y2Inc, data[l].y2Exp); });
    const chartContainer = document.getElementById('overviewChartContainer'); chartContainer.innerHTML = '';

    labels.forEach(l => {
        const d = data[l]; const hasData = d.y1Inc > 0 || d.y1Exp > 0 || d.y2Inc > 0 || d.y2Exp > 0;
        const h1Inc = (d.y1Inc / maxVal) * 100 * 0.85; const h1Exp = (d.y1Exp / maxVal) * 100 * 0.85;
        let h2Inc = 0; let h2Exp = 0;
        if (isCompare) { h2Inc = (d.y2Inc / maxVal) * 100 * 0.85; h2Exp = (d.y2Exp / maxVal) * 100 * 0.85; }
        
        let groupHTML = `<div class="chart-bar-group">`;
        if (hasData) {
            const maxH = Math.max(h1Inc, h1Exp, h2Inc, h2Exp);
            let tooltipHTML = `<div class="chart-tooltip" style="bottom: ${maxH}%; margin-bottom: 12px;"><div class="tooltip-month">${l} ${timeframe !== 'yearly' ? year1 : ''}</div><div class="tooltip-income">Income: ${userCurrency}${d.y1Inc.toLocaleString()}</div><div class="tooltip-expense">Expenses: ${userCurrency}${d.y1Exp.toLocaleString()}</div>`;
            if (isCompare) tooltipHTML += `<div style="margin-top:6px; border-top:1px solid #e5e7eb; padding-top:6px;"><div class="tooltip-month">${l} ${year2}</div><div class="tooltip-income">Income: ${userCurrency}${d.y2Inc.toLocaleString()}</div><div class="tooltip-expense">Expenses: ${userCurrency}${d.y2Exp.toLocaleString()}</div></div>`;
            groupHTML += tooltipHTML + `</div>`;
        }
        
        groupHTML += `<div class="bars-wrapper" style="display: flex; gap: 4px; align-items: flex-end; justify-content: center; height: 100%;">`;
        groupHTML += `<div class="chart-bar-income" style="height: ${h1Inc}%; width: 14px; background: #10b981; border-radius: 4px 4px 0 0;"></div>`;
        groupHTML += `<div class="chart-bar-expense" style="height: ${h1Exp}%; width: 14px; background: #ef4444; border-radius: 4px 4px 0 0;"></div>`;
        if (isCompare) {
            groupHTML += `<div class="chart-bar-income" style="height: ${h2Inc}%; width: 14px; background: #34d399; border-radius: 4px 4px 0 0; opacity: 0.6;"></div>`;
            groupHTML += `<div class="chart-bar-expense" style="height: ${h2Exp}%; width: 14px; background: #f87171; border-radius: 4px 4px 0 0; opacity: 0.6;"></div>`;
        }
        groupHTML += `</div><div class="bar-group-label">${l}</div></div>`; 
        chartContainer.innerHTML += groupHTML;
    });
}

